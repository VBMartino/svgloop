// Writes THIRD_PARTY_NOTICES.md: every runtime package (dependencies, recursively) with its version and license.
// The standalone binaries bundle all of these plus the Bun runtime; the npm package installs them as dependencies.
// Run: bun scripts/third-party-notices.ts
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const pkgJson = (dir: string) => JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
const seen = new Map<string, { version: string; license: string; homepage?: string }>();

function resolveDir(name: string, from: string): string | undefined {
  // Walk up node_modules folders like Node's resolver.
  let dir = from;
  while (true) {
    const p = join(dir, "node_modules", name);
    if (existsSync(join(p, "package.json"))) return p;
    const parent = join(dir, "..");
    if (parent === dir) return undefined;
    dir = parent;
  }
}

function walk(dir: string) {
  const p = pkgJson(dir);
  const deps = { ...(p.dependencies ?? {}), ...(p.optionalDependencies ?? {}) };
  for (const name of Object.keys(deps)) {
    const d = resolveDir(name, dir);
    if (!d) continue; // optional dependency for another platform
    const q = pkgJson(d);
    const key = `${q.name}@${q.version}`;
    if (seen.has(key)) continue;
    const license = typeof q.license === "string" ? q.license : q.license?.type ?? (q.licenses?.map((l: any) => l.type).join(" OR ") || "UNKNOWN");
    const repo = typeof q.repository === "string" ? q.repository : q.repository?.url;
    const source = (q.homepage ?? repo)?.replace(/^git\+/, "").replace(/\.git$/, "").replace(/^git@github\.com:/, "https://github.com/").replace(/^git:\/\//, "https://");
    seen.set(key, { version: q.version, license, homepage: source });
    walk(d);
  }
}
walk(root);

const rows = [...seen.entries()].sort(([a], [b]) => a.localeCompare(b));
const byLicense = new Map<string, number>();
for (const [, v] of rows) byLicense.set(v.license, (byLicense.get(v.license) ?? 0) + 1);

const md = `# Third-party notices

SVGLoop is licensed under Apache-2.0 (see \`LICENSE\` and \`NOTICE\`). It uses the open-source packages below.
The npm package installs them as dependencies; the standalone binaries from GitHub Releases bundle them,
together with the [Bun](https://bun.sh) runtime (see [Bun's license](https://bun.sh/docs/project/licensing), which covers
the components it embeds). Each package's full license text is in its own repository and in its npm tarball.

Notable: \`@resvg/resvg-js\` is MPL-2.0. SVGLoop uses it unmodified; its source is available at
https://github.com/yisibl/resvg-js.

Summary: ${[...byLicense.entries()].map(([l, n]) => `${l} (${n})`).join(", ")}

| Package | Version | License | Source |
|---|---|---|---|
${rows.map(([key, v]) => `| ${key.slice(0, key.lastIndexOf("@"))} | ${v.version} | ${v.license} | ${v.homepage ?? ""} |`).join("\n")}

_Generated by \`bun run notices\`._
`;
writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), md);
console.log(`THIRD_PARTY_NOTICES.md: ${rows.length} packages; ${[...byLicense.entries()].map(([l, n]) => `${l} ${n}`).join(", ")}`);
